/* 小方椅子：地图上有多少个 'c' 就生成多少把，全都能调查。
   共用一个 id（'chair'）—— 调查进度是全教室一起往前走的。 */
(function(){
    var chairs = [];
    FLOOR3.grid.forEach(function(row, ty){
        for (var tx = 0; tx < row.length; tx++){
            if (row.charAt(tx) !== 'c') continue;
            chairs.push({
                id:'chair', kind:'chair', x:tx + 0.5, y:ty + 0.5,
                set:'seenRoom', setTip:'可以回去锁门了',
                lines: CHAIR_LINES
            });
        }
    });
    FLOOR3.objects = FLOOR3.objects.concat(chairs);
})();
